import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseTSV, previewPaste, pasteDate, pasteRequestId } from '../src/lib/associate/paste';
import { validateEntry, warnings } from '../src/lib/associate/common';
import { putEntry, pendingEntries, removeEntry } from '../src/lib/associate/storage';
import type { Bundle, QueuedEntry } from '../src/lib/associate/types';
const bundle = { owner: 'me', ownerKey: 'me', leads: [{ id: 'lead', name: 'Existing Person', legacy_key: 'L1' }], partners: [{ id: 'cp', name: 'A CP', firm: 'Firm', legacy_key: 'C1' }], projects: [{ id: 'project', name: 'Kudal' }] } as unknown as Bundle;
test('customer guardrails are blockers; booking language and past dates are soft warnings', () => {
    const p = { name: 'New', occurred_on: '2026-10-24', rating_after: 'hot', plot_names: ['35'], next_action_date: '2026-10-25' };
    assert.deepEqual(validateEntry('customer', p), []);
    assert.ok(validateEntry('customer', { ...p, plot_names: [] }).length);
    assert.ok(validateEntry('customer', { ...p, next_action_date: '2026-11-01' }).length);
    assert.ok(validateEntry('customer', { ...p, rating_after: 'cold' }).some(e => e.includes('Cold reason')));
    assert.equal(warnings({ rating_after: 'cold', remark: 'Client paid token', next_action_date: '2020-01-01' }).length, 2);
    assert.deepEqual(validateEntry('customer', { ...p, rating_after: 'warm', next_action_date: '2020-01-01' }), []);
    assert.ok(validateEntry('booking', { name: 'New', plot_no: '35', booking_date: '2026-10-24', status: 'cancelled', source: 'direct' }).some(e => e.includes('cancellation')));
});
test('clipboard preserves quotes, embedded newlines and Hindi; old and flat headers validate', () => {
    assert.deepEqual(parseTSV('name\tremark\r\nOne\t"हिन्दी\nsecond\tline"'), [['name', 'remark'], ['One', 'हिन्दी\nsecond\tline']]);
    assert.equal(pasteDate('24/10/2026'), '2026-10-24');
    assert.equal(pasteDate('31/02/2026'), '31/02/2026');
    const rows = previewPaste('Customer Name\tMtg Date\tHWC\tPlot Name(s)\tNext Action Date\nExisting Person\t24/10/2026\tHot\t35|36\t25/10/2026', 'customer', bundle);
    assert.deepEqual(rows[0].errors, []);
    assert.equal(rows[0].payload.lead_id, 'lead');
    assert.deepEqual(rows[0].payload.plot_names, ['35', '36']);
    const denied = previewPaste('customer_name\tassociate_key\toccurred_on\trating_after\nOther\tother\t2026-10-24\twarm', 'customer', bundle);
    assert.ok(denied[0].errors.some(e => e.includes('another associate')));
    const book = previewPaste('Customer\tProject\tUnit/Plot #\tBooking Value\tBooking Date\tStatus\tSource\tCP Name\tRemarks\nExisting Person\tKudal\t35\t1,00,000\t24/10/2026\tBooking Done\tCP\tA CP\tDone', 'booking', bundle);
    assert.deepEqual(book[0].errors, []);
    assert.equal(book[0].payload.name, 'Existing Person');
    assert.equal(book[0].payload.cp_id, 'cp');
    assert.equal(book[0].payload.value, '100000');
    assert.equal(pasteRequestId('batch', 'row'), pasteRequestId('batch', 'row'));
    assert.notEqual(pasteRequestId('batch', 'row'), pasteRequestId('batch', 'other row'));
    assert.match(pasteRequestId('batch', 'row'), /^[0-9a-f-]{36}$/);
});
test('queue survives rereads, isolates accounts and removes one entry without losing siblings', () => {
    const store: Record<string, unknown> = Object.create(null);
    Object.defineProperties(store, { getItem: { value: (k: string) => store[k] ?? null }, setItem: { value: (k: string, v: string) => { store[k] = v; } }, removeItem: { value: (k: string) => { delete store[k]; } } });
    Object.defineProperty(globalThis, 'localStorage', { value: store, configurable: true });
    Object.defineProperty(globalThis, 'window', { value: new EventTarget(), configurable: true });
    const item = { owner: 'a', request_id: 'one', kind: 'customer', payload: { remark: 'हिन्दी draft' }, created_at: '2026-10-24' } as QueuedEntry;
    putEntry(item);
    putEntry(item);
    putEntry({ ...item, request_id: 'two' });
    putEntry({ ...item, owner: 'b' });
    assert.equal(pendingEntries('a').length, 2);
    assert.equal(pendingEntries('b').length, 1);
    assert.equal(pendingEntries('a')[0].payload.remark, 'हिन्दी draft');
    removeEntry('a', 'one');
    assert.equal(pendingEntries('a').length, 1);
    assert.equal(pendingEntries('b').length, 1);
});
