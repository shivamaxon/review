// Joins every file in supabase/migrations into ONE file you can paste into the Supabase SQL Editor.
// Usage: npm run db:bundle   ->  supabase/all_migrations.sql
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const files = readdirSync(join(root, "migrations")).filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ===================== ${f} =====================\n${readFileSync(join(root, "migrations", f), "utf8")}`).join("\n\n");
writeFileSync(join(root, "all_migrations.sql"), `-- Generated by \`npm run db:bundle\`. Do not edit: edit the files in supabase/migrations instead.\n\n${out.trimEnd()}\n`);
console.log(`Wrote supabase/all_migrations.sql (${files.length} migrations, ${out.length} bytes)`);
